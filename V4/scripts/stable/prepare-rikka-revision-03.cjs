const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '../../..');
const work = path.join(root, 'V4/template-stable/rikka-revision-03');
const read = p => JSON.parse(fs.readFileSync(path.resolve(root, p), 'utf8').replace(/^\uFEFF/, ''));
const hash = p => crypto.createHash('sha256').update(fs.readFileSync(path.resolve(root, p))).digest('hex');
const write = (p, v) => fs.writeFileSync(path.resolve(root, p), JSON.stringify(v, null, 2));
const registry = read('V4/template-stable/registry-electro-03e.json');
const baseTemplate = registry.template;
const card = read('V4/template-stable/rikka-revision-02/card.json');
const baseCard = 'V4/templates/' + card.output + '.psd';
const previousPNG = 'V4/cartes/' + card.output + '.png';
const framing = read(path.join(work, 'framing.json'));
card.output = 'RIKKA_V4_03_RECADRAGE';
card.revisionNote = 'Illustration translatee de 55 px vers la droite, sans redimensionnement ni regeneration. Fouet et Kalistel visibles. Cadre, icones et statistiques inchanges.';
registry.template = 'V4/template-stable/KALISTAR_V4_TEMPLATE_03F_ELECTRO_RIKKA.psd';
registry.artworkRevision = 'RIKKA revision 03 - recentrage fouet et Kalistel';
const art = registry.artworkAssets.RIKKA;
art.placement.centerX = (framing.after[0] + framing.after[2]) / 2;
art.framing = { translation: framing.delta, bounds: framing.after, method: 'Native PSD smart-object translation; original embedded pixels and scale retained.' };
write('V4/template-stable/registry-electro-03f.json', registry);
write(path.join(work, 'card.json'), card);
const previous = read('V4/template-stable/rikka-revision-02/sources.json');
const paths = [...new Set([...Object.keys(previous.protectedFiles), baseTemplate, baseCard, previousPNG, 'V4/template-stable/registry-electro-03e.json', card.artworkSource])];
const proof = path.join(work, 'sources.json');
if (fs.existsSync(proof)) {
  for (const [p, h] of Object.entries(read(proof).protectedFiles)) if (hash(p) !== h) throw Error('Source modifiee : ' + p);
} else write(proof, { baseTemplate, baseCard, previousPNG, artwork: card.artworkSource, protectedFiles: Object.fromEntries(paths.map(p => [p, hash(p)])) });
console.log(JSON.stringify({ output: card.output, placement: art.placement, preservedFiles: paths.length }));
