'use strict';
const assert=require('node:assert/strict');
const T=require('./trophies.js'),S=require('./statistics.js');
const unit=(uid,values={})=>({uid,instanceId:uid,participated:true,...values});
const summary={complete:true,partial:false,units:[unit('a',{rating:12,kills:2,holds:3,clovers:1,hearts:0}),unit('b',{rating:12,kills:2,holds:1,clovers:1,hearts:0}),unit('reserve',{rating:999,kills:999,participated:false})]};
assert.deepEqual(T.awards(summary),{a:['crystal','killer','blocker','clover'],b:['crystal','killer','clover']});
assert.deepEqual(T.awards({...summary,complete:false}),{});
assert.deepEqual(T.awards({...summary,partial:true}),{});
assert.deepEqual(T.awards({complete:true,units:[unit('a')]}),{});
assert.deepEqual(T.leaders(summary,'hearts'),[]);
const result=T.empty();T.add(result,{side:0,winner:0,kills:3,physical:2},['crystal','crystal','heart']);
assert.equal(result.trophies.crystal,1);assert.equal(result.trophies.heart,1);assert.equal(result.mvp,1);
const cards=[{id:'a',characterId:'momo',name:'MOMO',title:'A',element:'ELECTRO',faction:'CHROMA'},{id:'b',characterId:'momo',name:'MOMO',title:'B',element:'ELECTRO',faction:'CHROMA'},{id:'c',characterId:'cloud',name:'CLOUD',title:'C',element:'NONE',faction:'FF7'}];
const history=(id,kills,matchId='match')=>({cardId:id,kills,matchId,side:0,winner:0,participated:true,partial:false,finishedAt:'2026-09-22T00:00:00Z',trophies:['killer']});
const db={instances:()=>[{}],matches:()=>[{id:'match',finalized:true,summary:{partial:false,units:[]}}],career:id=>({history:id==='a'?[history(id,4)]:id==='b'?[history(id,2),history(id,6),{...history(id,999,'partial'),partial:true}]:[]})};
const state={...S.defaults},rows=S.rows({cards},db,state,Date.parse('2026-09-22T12:00:00Z'));
assert.equal(rows.length,2);assert.equal(rows[0].games,3);assert.equal(rows[0].kills,12);
assert.equal(rows[0].trophies.killer,3);
assert.equal(S.value(rows[0],S.groups.performance.find(c=>c.key==='kills'),'average'),4);
assert.equal(S.value(rows[1],S.groups.performance.find(c=>c.key==='kills'),'average'),null);
assert.equal(S.rows({cards},db,{...state,grouping:'version'}).length,3);
assert.equal(S.rows({cards},db,{...state,collab:'FF7'}).length,1);
assert.equal(S.rows({cards},db,{...state,minimum:1}).length,1);
assert.equal(S.rows({cards},db,{...state,query:'introuvable'}).length,0);
assert.equal(S.rows({cards},db,{...state,period:'30'},Date.parse('2026-12-22')).every(r=>r.games===0),true);
const transferred={...db,matches:()=>[],career:id=>({history:id==='a'?[history(id,9,'previous-owner-match')]:[]})};
assert.equal(S.rows({cards},transferred,state)[0].kills,9,'owned collectibles retain the previous owner career');
assert.equal(S.rows({cards},transferred,{...state,scope:'all'}).every(r=>r.games===0),true,'all-team archives never expose another profile matches');
assert.equal(S.sorted(rows,{...state,sort:'kills'})[0].card.name,'MOMO');
assert.equal(S.sorted(rows,{...state,sort:'kills',direction:'asc'})[0].card.name,'MOMO','no-game rows stay last');
const csv=S.csv([{...rows[0],card:{...cards[0],name:'=FORMULA()'}}],state);
assert.ok(csv.startsWith('\ufeff'));assert.ok(csv.includes('"\'=FORMULA()"'));assert.ok(csv.includes('4,0'));
assert.ok(S.csv([{...rows[0],card:{...cards[0],name:'  =FORMULA()'}}],state).includes('"\'  =FORMULA()"'));
console.log('PASS: honours, ties, positive-only thresholds, completed/full history, aggregates, one-decimal averages, filters, ordering and safe Excel CSV.');
