'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {createRequire}=require('node:module');
const runtime=process.env.KALISTAR_NODE_MODULES||path.join(process.env.USERPROFILE,'.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules');
const {chromium}=createRequire(path.join(runtime,'__phone_preview__.cjs'))('playwright');
const url=process.env.KALISTAR_URL||'http://127.0.0.1:4304';
const output=path.join(__dirname,'verification/razr50');
let browser;
async function main(){
  fs.mkdirSync(output,{recursive:true});
  browser=await chromium.launch({channel:'chrome',headless:true});
  const context=await browser.newContext({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
  const page=await context.newPage(),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(url+'/jeu/#arena');
  await page.waitForFunction(()=>window.KALISTAR_READY);
  const saved=await page.evaluate(()=>localStorage.getItem('kalistar.v4.game'));
  await page.locator('[data-action=phone-preview]').click();
  await page.waitForSelector('#phone-preview-frame');
  const frame=await page.locator('#phone-preview-frame').contentFrame();
  await frame.locator('[data-action=start]').waitFor();
  assert.deepEqual(await frame.locator('body').evaluate(()=>[innerWidth,innerHeight]),[412,1007]);
  assert.equal(await frame.locator('body').evaluate(()=>localStorage.getItem('kalistar.v4.game')),saved);
  assert.equal(await page.evaluate(()=>!!window.KALISTAR_DB),false,'host never starts a second game');
  await frame.locator('body').evaluate(()=>{window.testPreviewSession='same document';});
  await page.screenshot({path:path.join(output,'arena-preview.png')});
  await page.locator('#phone-preview-toggle').click();
  await frame.locator('body').evaluate(()=>new Promise(resolve=>requestAnimationFrame(resolve)));
  assert.equal(await frame.locator('body').evaluate(()=>innerWidth),1440);
  assert.equal(await frame.locator('body').evaluate(()=>window.testPreviewSession),'same document');
  await frame.locator('[data-action=phone-preview]').click();
  await page.waitForFunction(()=>document.getElementById('phone-preview-toggle').getAttribute('aria-pressed')==='true');
  assert.equal(await frame.locator('body').evaluate(()=>window.testPreviewSession),'same document');
  await page.setViewportSize({width:1024,height:700});
  const bounds=await page.locator('#phone-preview-frame').boundingBox();
  assert.ok(bounds.y>=52&&bounds.x>=0&&bounds.y+bounds.height<=700&&bounds.x+bounds.width<=1024,'device fits the host screen');
  assert.deepEqual(await frame.locator('body').evaluate(()=>[innerWidth,innerHeight]),[412,1007]);
  await page.setViewportSize({width:1440,height:1000});
  await frame.locator('[data-action=arena-menu]').click();
  await frame.locator('#mobile-dialog [data-action=match-stats]').click();
  for(const tab of ['awards','teams','lineup','definitions']){
    await frame.locator('[data-action=stats-tab][data-id='+tab+']').click();
    assert.equal(await frame.locator('#match-dialog .match-pagination').count(),0);
    if(tab==='awards')assert.equal(await frame.locator('.match-palmares article:visible').count(),5);
    if(tab==='lineup')assert.equal(await frame.locator('[data-stat-unit]').count(),20);
  }
  // Synthetic ties only in this disposable browser DOM, never in the registry.
  await frame.locator('body').evaluate(()=>{
    const s=JSON.parse(localStorage.getItem('kalistar.v4.game'));
    s.phase='over';s.winner=0;
    s.players.forEach(p=>p.board.filter(Boolean).forEach(u=>{u.entered=true;}));
    s.match.events=[0,1].map(i=>({round:i+1,attacker:s.players[0].board[i].uid,target:s.players[1].board[i].uid,attackRolls:1,defenseRolls:1,attack:250,defense:100,breakthrough:150,buff:0,kill:true,hold:false,dodge:false,shield:false,reraise:false,luck:false,barrier:0,debuff:0,support:null}));
    window.testReportState=s;
    document.querySelector('#match-dialog .match-report').outerHTML=KalistarMatchReport.render(s,{tab:'awards'});lucide.createIcons();
  });
  assert.equal(await frame.locator('[data-trophy=crystal] .golden-winners button').count(),1,'MVP stays unique');
  assert.equal(await frame.locator('[data-trophy=killer] .golden-winners button').count(),2,'both tied killers are included');
  assert.equal(await frame.locator('.match-palmares article:visible').count(),5);
  assert.ok(await frame.locator('.match-view').evaluate(n=>n.scrollHeight>n.clientHeight));
  await frame.locator('.award-art').first().evaluate(img=>img.decode());
  await page.screenshot({path:path.join(output,'palmares-preview.png')});
  await frame.locator('.match-view').evaluate(n=>{n.scrollTop=n.scrollHeight;});
  const last=await frame.locator('.match-palmares article').last().boundingBox();
  const view=await frame.locator('.match-view').boundingBox();
  assert.ok(last.y+last.height<=view.y+view.height+1,'last distinction is reachable');
  await page.screenshot({path:path.join(output,'palmares-bottom.png')});
  await page.locator('#phone-preview-toggle').click();
  await frame.locator('body').evaluate(()=>{
    document.querySelector('#match-dialog .match-report').outerHTML=KalistarMatchReport.render(window.testReportState,{tab:'awards'});lucide.createIcons();
  });
  assert.equal(await frame.locator('.match-palmares article').count(),5,'desktop retains its five-window composition');
  assert.equal(await frame.locator('.match-palmares .match-pagination').count(),0,'shared trophies keep every winner together');
  assert.equal(await frame.locator('.match-report').getAttribute('data-report-pages'),'1');
  assert.equal(await frame.locator('body').evaluate(()=>localStorage.getItem('kalistar.v4.game')),saved,'preview and report do not change the match');
  await frame.locator('#match-dialog > .dialog-head [data-action=close]').click();
  await page.setViewportSize({width:360,height:740});
  await page.waitForTimeout(200);
  assert.ok(await page.locator('#phone-preview-toggle').isVisible(),'toggle remains reachable in a narrow host window');
  await frame.locator('[data-action=arena-menu]').click();
  await frame.locator('#mobile-dialog [data-action=match-stats]').click();
  await frame.locator('[data-action=stats-tab][data-id=lineup]').click();
  await frame.locator('.match-unit img').last().evaluate(img=>img.decode());
  await frame.locator('.match-view').evaluate(n=>{n.scrollTop=n.scrollHeight;});
  await page.screenshot({path:path.join(output,'phone-lineup-bottom.png')});
  const lastRow=await frame.locator('[data-stat-unit]').last().boundingBox();
  const tableView=await frame.locator('.match-view').boundingBox();
  assert.ok(lastRow.y+lastRow.height<=tableView.y+tableView.height+1,'last phone table row is reachable: '+JSON.stringify({lastRow,tableView}));
  assert.equal(await frame.locator('.match-pagination').count(),0);
  await page.locator('#phone-preview-toggle').click();
  assert.deepEqual(await frame.locator('body').evaluate(()=>[innerWidth,innerHeight]),[412,1007]);
  assert.deepEqual(errors,[]);
  console.log('PASS: Razr 50 toggle, same-session resize, saved match, host fit, continuous mobile report, all ties, desktop pagination.');
}
main().catch(e=>{console.error(e);process.exitCode=1;}).finally(async()=>{await browser?.close();});
