'use strict';
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict'),{execFileSync}=require('node:child_process'),config=require('./release.json');
const root=path.resolve(__dirname,'../../..'),release='V4/releases/2026-10-11-v4.6.22';
const proof=require('../../revisions/2026-10-11-chrono-equipment/media-provenance.json');
const git=(args,extra={})=>execFileSync('git',args,{cwd:root,encoding:'utf8',maxBuffer:32*1024*1024,...extra}).trim();
assert.equal(git(['remote','get-url','origin']),config.repository);assert.equal(git(['branch','--show-current']),'main');
assert.equal(git(['ls-remote','origin','refs/heads/main']).split(/\s+/)[0],git(['rev-parse','HEAD']));
assert(git(['show','HEAD:V4/site/index.html']).includes('VERSION '+config.previousVersion));
const media=[...new Set(proof.assets.flatMap(a=>[a.source,a.file]))],workflow='.github/workflows/pages.yml';
const paths=[...config.scope,...media,release];
const scoped=p=>p===workflow||config.versionFiles.includes(p)||paths.some(x=>p===x||p.startsWith(x+'/'));
const prior=git(['diff','--cached','--name-only','-z']).split('\0').filter(Boolean);
if(process.argv.includes('--refresh'))assert(prior.every(scoped));else assert.equal(prior.length,0);
git(['add','--',...paths,...config.versionFiles]);
const before=execFileSync('git',['show','HEAD:'+workflow],{cwd:root,encoding:'utf8'});
const anchor='          node --test V4/site/castlevania-kalistar-equipment.test.cjs',line='          node --test V4/site/chrono-equipment.test.cjs';
assert(before.includes(anchor)&&!before.includes(line));
const after=before.replace(anchor,anchor+(before.includes('\r\n')?'\r\n':'\n')+line);
const oid=git(['hash-object','-w','--stdin'],{input:after});git(['update-index','--cacheinfo','100644',oid,workflow]);
const staged=git(['diff','--cached','--name-only','-z']).split('\0').filter(Boolean);assert(staged.every(scoped));
git(['diff','--cached','--check']);console.log(JSON.stringify({files:staged.length,version:config.version,unrelatedChangesPreserved:true}));
