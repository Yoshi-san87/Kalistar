'use strict';
const fs = require('node:fs'), path = require('node:path'), assert = require('node:assert/strict');
const crypto = require('node:crypto');
const entry = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));
const registry = path.join(__dirname, 'revisions.json');
const data = JSON.parse(fs.readFileSync(registry, 'utf8'));
const original = require('./provenance/' + entry.key + '.json');
const chain = data.revisions.filter(r => r.key === entry.key);
assert.equal(entry.previousFile, chain.at(-1)?.file || original.file);
const target = path.resolve(__dirname, entry.file);
assert(target.startsWith(path.join(__dirname, 'images') + path.sep));
assert(!data.revisions.some(r => r.file === entry.file));
const bytes = fs.readFileSync(entry.source);
assert(bytes.subarray(1, 4).equals(Buffer.from('PNG')));
if (fs.existsSync(target)) assert(fs.readFileSync(target).equals(bytes));
else fs.copyFileSync(entry.source, target, fs.constants.COPYFILE_EXCL);
entry.sha256 = crypto.createHash('sha256').update(bytes).digest('hex');
data.revisions.push(entry);
fs.writeFileSync(registry, JSON.stringify(data, null, 2) + '\n');
console.log(JSON.stringify({key:entry.key, file:entry.file, sha256:entry.sha256}));
