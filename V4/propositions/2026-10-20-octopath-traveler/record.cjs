'use strict';
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const assert = require('node:assert/strict');
const batch = require('./prompts.json');
const index = Number(process.argv[2]);
const source = process.argv[3];
const character = batch.characters[index];
assert(character && source && path.isAbsolute(source), 'Expected character index and generated source');
const target = path.resolve(__dirname, character.file);
const proof = path.join(__dirname, 'provenance', character.key + '.json');
assert(!fs.existsSync(target) && !fs.existsSync(proof), 'Never overwrite a generated proposal');
const bytes = fs.readFileSync(source);
assert(bytes.subarray(1,4).equals(Buffer.from('PNG')));
const width = bytes.readUInt32BE(16), height = bytes.readUInt32BE(20);
assert(width >= 700 && height > width);
fs.mkdirSync(path.dirname(target), {recursive:true});
fs.mkdirSync(path.dirname(proof), {recursive:true});
fs.copyFileSync(source, target, fs.constants.COPYFILE_EXCL);
const sha256 = crypto.createHash('sha256').update(bytes).digest('hex');
const record = {key:character.key,name:character.name,file:character.file,source,generator:batch.generator,prompt:character.prompt,styleReferences:batch.styleReferences,width,height,sha256,status:'illustrated-for-author-review'};
fs.writeFileSync(proof, JSON.stringify(record,null,2) + '\n', {flag:'wx'});
console.log(JSON.stringify({name:character.name,file:character.file,width,height,sha256}));
